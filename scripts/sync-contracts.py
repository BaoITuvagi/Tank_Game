"""Generate matching gameplay constants; --check verifies without changing files."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rules = json.loads((ROOT / 'source/shared/game-rules.json').read_text(encoding='utf-8'))
java = ['package tank;', '// Generated by scripts/sync-contracts.py; edit source/shared/game-rules.json.', 'public final class GameRules {', ' private GameRules() {}']
csharp = ['namespace Tank {', ' // Generated by scripts/sync-contracts.py; edit source/shared/game-rules.json.', ' public static class GameRules {']
for name, value in rules.items():
    kind = 'int' if isinstance(value, int) else 'float'
    literal = str(value) + ('' if kind == 'int' else 'f')
    java.append(f' public static final {kind} {name}={literal};')
    csharp.append(f'  public const {kind} {name}={literal};')
java.append('}')
csharp += [' }', '}']
outputs = {
    ROOT / 'source/server/src/main/java/tank/GameRules.java': '\n'.join(java) + '\n',
    ROOT / 'source/client/Assets/Scripts/GameRules.cs': '\n'.join(csharp) + '\n',
}
check = argparse.ArgumentParser()
check.add_argument('--check', action='store_true')
args = check.parse_args()
for path, content in outputs.items():
    if args.check:
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            raise SystemExit(f'Generated contract is out of date: {path}')
    else:
        path.write_text(content, encoding='utf-8')
print('Gameplay contracts match.' if args.check else 'Generated Java/C# gameplay contracts.')
