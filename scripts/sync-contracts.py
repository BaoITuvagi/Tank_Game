"""Generate matching gameplay constants; --check verifies without changing files."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rules = json.loads((ROOT / 'source/shared/game-rules.json').read_text(encoding='utf-8'))
java = ['package tank;', '// Generated by scripts/sync-contracts.py; edit source/shared/game-rules.json.', 'public final class GameRules {', ' private GameRules() {}']
csharp = ['namespace Tank {', ' // Generated by scripts/sync-contracts.py; edit source/shared/game-rules.json.', ' public static class GameRules {']
for name, value in rules.items():
    kind = 'int' if isinstance(value, int) else 'float'
    literal = str(value) + ('' if kind == 'int' else 'f')
    java.append(f' public static final {kind} {name}={literal};')
    csharp.append(f'  public const {kind} {name}={literal};')
java.append('}')
csharp += [' }', '}']
outputs = {
    ROOT / 'source/server/src/main/java/tank/GameRules.java': '\n'.join(java) + '\n',
    ROOT / 'source/client/Assets/Scripts/GameRules.cs': '\n'.join(csharp) + '\n',
}
content = json.loads((ROOT / 'source/shared/roleplay-content.json').read_text(encoding='utf-8'))
nations = content['nations']
if [n['id'] for n in nations] != list(range(8)):
    raise SystemExit('Content must define nations 0-7 in order.')
if not isinstance(content['version'], int) or not 1 <= content['version'] <= 65535:
    raise SystemExit('Content version must fit u16.')
for entry in nations:
    if not entry.get('name') or not entry.get('description'):
        raise SystemExit('Content names and descriptions are required.')
    for field in ('cooldownTicks', 'durationTicks'):
        value = entry[field]
        if type(value) is not int or value < 0 or (field == 'cooldownTicks' and value == 0):
            raise SystemExit(f'Invalid {field}: {entry["id"]}')
        if rules['MaxMatchTicks'] + value > 65535:
            raise SystemExit(f'Deadline exceeds u16: {entry["id"]}')
if not content['requiredSprites'] or len(set(content['requiredSprites'])) != len(content['requiredSprites']):
    raise SystemExit('Required sprite names must be nonempty and unique.')
canonical = json.dumps({'rules': rules, 'content': content}, ensure_ascii=False,
                       sort_keys=True, separators=(',', ':')).encode('utf-8')
content_hash = hashlib.sha256(canonical).hexdigest()
java_content = ['package tank;', '// Generated by scripts/sync-contracts.py; edit source/shared/roleplay-content.json.',
                'public final class RoleplayContent {', ' private RoleplayContent() {}',
                f' public static final int Version={content["version"]};',
                f' public static final String Hash="{content_hash}";']
cs_content = ['namespace Tank {', ' // Generated by scripts/sync-contracts.py; edit source/shared/roleplay-content.json.',
              ' public static class RoleplayContent {', f'  public const int Version={content["version"]};',
              f'  public const string Hash="{content_hash}";']
story = json.dumps(content['story'], ensure_ascii=False)
java_content.append(f' public static final String Story={story};')
cs_content.append(f'  public const string Story={story};')
arrays = [('RequiredSprites', 'String', content['requiredSprites'])]
for prefix, entries in [('Nation', nations)]:
    for suffix, field, kind in [('Ids', 'id', 'int'), ('Names', 'name', 'String'),
                                ('Descriptions', 'description', 'String'),
                                ('Cooldowns', 'cooldownTicks', 'int'), ('Durations', 'durationTicks', 'int')]:
        arrays.append((prefix + suffix, kind, [entry[field] for entry in entries]))
arrays.append(('QNames', 'String', [entry['skill'] for entry in nations]))
for name, kind, values in arrays:
    literal = ','.join(json.dumps(value, ensure_ascii=False) for value in values)
    java_content.append(f' public static final {kind}[] {name}={{ {literal} }};')
    cs_kind = 'string' if kind == 'String' else kind
    cs_content.append(f'  public static readonly {cs_kind}[] {name}={{ {literal} }};')
java_content.append('}')
cs_content += [' }', '}']
outputs[ROOT / 'source/server/src/main/java/tank/RoleplayContent.java'] = '\n'.join(java_content) + '\n'
outputs[ROOT / 'source/client/Assets/Scripts/RoleplayContent.cs'] = '\n'.join(cs_content) + '\n'
check = argparse.ArgumentParser()
check.add_argument('--check', action='store_true')
args = check.parse_args()
for path, content in outputs.items():
    if args.check:
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            raise SystemExit(f'Generated contract is out of date: {path}')
    else:
        path.write_text(content, encoding='utf-8')
print('Gameplay contracts match.' if args.check else 'Generated Java/C# gameplay contracts.')
